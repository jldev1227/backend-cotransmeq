-- Módulo de incidentes: accidentes, incidentes y casi-accidentes con su investigación.
--
-- Reutiliza `pesv_incident`, que quedó vacía al retirar el PESV (ver el
-- comentario del modelo en schema.prisma), y le añade lo que faltaba: tipo,
-- estado, autoridad e IPAT, la investigación (Res. 1401/2007) y el cierre.
-- Dos tablas hijas: evidencias en S3 y acciones correctivas vinculadas.
--
-- Idempotente y aditiva: no borra ni reescribe filas. Aplicar a mano en una
-- transacción (`psql --single-transaction`) y registrar con `migrate resolve`.

-- ── Tipos ──────────────────────────────────────────────────────────────
DO $$ BEGIN
  CREATE TYPE enum_incidente_tipo AS ENUM ('ACCIDENTE_TRANSITO', 'INCIDENTE', 'CASI_ACCIDENTE');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE enum_incidente_estado AS ENUM ('REPORTADO', 'EN_INVESTIGACION', 'CERRADO');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- ── pesv_incident deja de colgar de un ciclo PESV ──────────────────────
ALTER TABLE pesv_incident ALTER COLUMN cycle_id DROP NOT NULL;
-- Un casi-accidente no tiene severidad: no hubo daños ni lesiones.
ALTER TABLE pesv_incident ALTER COLUMN severidad DROP NOT NULL;

-- Borrar un ciclo PESV no puede llevarse reportes de accidentes en cascada.
DO $$ BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'pesv_incident_cycle_id_fkey' AND confdeltype = 'c'
  ) THEN
    ALTER TABLE pesv_incident DROP CONSTRAINT pesv_incident_cycle_id_fkey;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pesv_incident_cycle_id_fkey') THEN
    ALTER TABLE pesv_incident ADD CONSTRAINT pesv_incident_cycle_id_fkey
      FOREIGN KEY (cycle_id) REFERENCES pesv_cycle(id) ON UPDATE CASCADE ON DELETE SET NULL;
  END IF;
END $$;

-- `municipio_id` existía sin llave foránea.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pesv_incident_municipio_id_fkey') THEN
    ALTER TABLE pesv_incident ADD CONSTRAINT pesv_incident_municipio_id_fkey
      FOREIGN KEY (municipio_id) REFERENCES municipios(id) ON UPDATE CASCADE ON DELETE SET NULL;
  END IF;
END $$;

-- ── Radicado: `consecutivo` pasa a columna de identidad ────────────────
-- IDENTITY y no una secuencia suelta: la secuencia queda ligada a la columna
-- y al dueño de la tabla, así que no hay que conceder USAGE a un rol que se
-- llama distinto en cada base (en local el dueño ni siquiera es quien migra).
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'pesv_incident'
      AND column_name = 'consecutivo' AND is_identity = 'YES'
  ) THEN
    UPDATE pesv_incident p SET consecutivo = s.n
    FROM (
      SELECT id, COALESCE((SELECT max(consecutivo) FROM pesv_incident), 0)
                 + row_number() OVER (ORDER BY created_at, id) AS n
      FROM pesv_incident WHERE consecutivo IS NULL
    ) s
    WHERE p.id = s.id;
    ALTER TABLE pesv_incident ALTER COLUMN consecutivo SET NOT NULL;
    ALTER TABLE pesv_incident ALTER COLUMN consecutivo ADD GENERATED BY DEFAULT AS IDENTITY;
    PERFORM setval(
      pg_get_serial_sequence('public.pesv_incident', 'consecutivo'),
      GREATEST(COALESCE((SELECT max(consecutivo) FROM pesv_incident), 0), 1),
      (SELECT max(consecutivo) IS NOT NULL FROM pesv_incident)
    );
  END IF;
END $$;

-- ── Columnas del reporte, la investigación y el cierre ─────────────────
ALTER TABLE pesv_incident
  ADD COLUMN IF NOT EXISTS tipo enum_incidente_tipo NOT NULL DEFAULT 'ACCIDENTE_TRANSITO',
  ADD COLUMN IF NOT EXISTS estado enum_incidente_estado NOT NULL DEFAULT 'REPORTADO',
  ADD COLUMN IF NOT EXISTS terceros_detalle JSONB,
  ADD COLUMN IF NOT EXISTS autoridad VARCHAR(120),
  ADD COLUMN IF NOT EXISTS numero_informe VARCHAR(60),
  ADD COLUMN IF NOT EXISTS equipo_investigador JSONB,
  ADD COLUMN IF NOT EXISTS actos_inseguros TEXT,
  ADD COLUMN IF NOT EXISTS condiciones_inseguras TEXT,
  ADD COLUMN IF NOT EXISTS factores_personales TEXT,
  ADD COLUMN IF NOT EXISTS factores_trabajo TEXT,
  ADD COLUMN IF NOT EXISTS analisis_porques JSONB,
  ADD COLUMN IF NOT EXISTS lecciones_aprendidas TEXT,
  ADD COLUMN IF NOT EXISTS investigacion_iniciada_at TIMESTAMPTZ(6),
  ADD COLUMN IF NOT EXISTS fecha_cierre DATE,
  ADD COLUMN IF NOT EXISTS responsable_cierre VARCHAR(255),
  ADD COLUMN IF NOT EXISTS observaciones_cierre TEXT,
  ADD COLUMN IF NOT EXISTS cerrado_por_id UUID;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pesv_incident_cerrado_por_id_fkey') THEN
    ALTER TABLE pesv_incident ADD CONSTRAINT pesv_incident_cerrado_por_id_fkey
      FOREIGN KEY (cerrado_por_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS pesv_incident_estado_fecha_idx ON pesv_incident (estado, fecha);
CREATE INDEX IF NOT EXISTS pesv_incident_tipo_fecha_idx ON pesv_incident (tipo, fecha);

-- ── Evidencias ─────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS incidente_evidencias (
  id UUID NOT NULL,
  incidente_id UUID NOT NULL,
  s3_key VARCHAR(500) NOT NULL,
  nombre_original VARCHAR(255) NOT NULL,
  mimetype VARCHAR(100) NOT NULL,
  tamano INTEGER NOT NULL DEFAULT 0,
  descripcion VARCHAR(500),
  subido_por_id UUID,
  deleted_at TIMESTAMPTZ(6),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT incidente_evidencias_pkey PRIMARY KEY (id),
  CONSTRAINT incidente_evidencias_incidente_id_fkey FOREIGN KEY (incidente_id)
    REFERENCES pesv_incident(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT incidente_evidencias_subido_por_id_fkey FOREIGN KEY (subido_por_id)
    REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS incidente_evidencias_incidente_id_idx ON incidente_evidencias (incidente_id);
CREATE INDEX IF NOT EXISTS incidente_evidencias_deleted_at_idx ON incidente_evidencias (deleted_at);

-- ── Acciones correctivas vinculadas ────────────────────────────────────
CREATE TABLE IF NOT EXISTS incidente_acciones (
  incidente_id UUID NOT NULL,
  accion_id UUID NOT NULL,
  creada_desde_incidente BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT incidente_acciones_pkey PRIMARY KEY (incidente_id, accion_id),
  CONSTRAINT incidente_acciones_incidente_id_fkey FOREIGN KEY (incidente_id)
    REFERENCES pesv_incident(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT incidente_acciones_accion_id_fkey FOREIGN KEY (accion_id)
    REFERENCES acciones_correctivas_preventivas(id) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS incidente_acciones_accion_id_idx ON incidente_acciones (accion_id);
